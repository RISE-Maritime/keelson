#!/usr/bin/env python3
"""Every subject's key shape and storage, from the two places they are stated.

A subject a protocol specifies (protocols/*.yaml) takes its key rows from that
protocol: the protocol is the source, and nothing has to repeat it. Every other
subject takes its rows from messages/subject_keys.yaml, or that file's
`default`. Where subject_keys.yaml still lists a protocol's subject, the
protocol's rows win — so a protocol added on another branch never has to touch
subject_keys.yaml for the SDKs to answer for its subjects.

Usage (the SDK generators):
    build_subject_keys.py --yaml <out>   the merged table, for the Python SDK
    build_subject_keys.py --json <out>   the same, for the JavaScript SDK
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))

from protocols_lib import load_all  # noqa: E402


def protocol_rows(protocols_dir: Path = REPO / "protocols") -> dict:
    """{subject: [{key, shape, storage}, ...]} from every protocol's keys."""
    out: dict = {}
    for protocol in load_all(protocols_dir):
        for row in protocol.data.get("keys") or []:
            subject = row.get("subject")
            if not subject:
                continue
            entry = {k: row[k] for k in ("key", "shape", "storage") if k in row}
            rows = out.setdefault(subject, [])
            if entry not in rows:
                rows.append(entry)
    return out


def merged(
    subject_keys_path: Path = REPO / "messages" / "subject_keys.yaml",
    protocols_dir: Path = REPO / "protocols",
) -> dict:
    """subject_keys.yaml's document, with every protocol subject's rows taken
    from its protocol."""
    doc = yaml.safe_load(subject_keys_path.read_text()) or {}
    subjects = dict(doc.get("subjects") or {})
    subjects.update(protocol_rows(protocols_dir))
    return {"default": doc.get("default") or [], "subjects": subjects}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--yaml", type=Path)
    group.add_argument("--json", type=Path)
    args = parser.parse_args()
    doc = merged()
    if args.yaml:
        args.yaml.write_text(
            "# Generated by scripts/build_subject_keys.py; do not edit.\n"
            + yaml.safe_dump(doc, sort_keys=True)
        )
    else:
        args.json.write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
